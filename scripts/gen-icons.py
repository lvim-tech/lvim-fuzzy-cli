#!/usr/bin/env python3
"""Generate src/icons.rs from lvim-icons' data (the ecosystem's one icon
source): the file names, the extensions and the special kinds, each with its
Nerd Font glyph and palette role. The glyphs are written as \\u{...} escapes,
so no editor or tool can drop them.

    scripts/gen-icons.py [PATH_TO_LVIM_ICONS]   (default: ../lvim-icons)
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "..", "lvim-icons")
data = os.path.join(root, "lua", "lvim-icons", "data")
pat = re.compile(r'^\s*(?:\["([^"]+)"\]|([A-Za-z0-9_]+))\s*=\s*\{\s*glyph\s*=\s*"([^"]+)"\s*,\s*role\s*=\s*"(\w+)"')


def read(name):
    out = {}
    with open(os.path.join(data, name), encoding="utf-8") as f:
        for line in f:
            m = pat.match(line)
            if m:
                out[m.group(1) or m.group(2)] = (m.group(3), m.group(4))
    if not out:
        sys.exit(f"no icons read from {name}")
    return out


def esc(s):
    return "".join(c if c.isascii() and c not in '"\\' else "\\u{%x}" % ord(c) for c in s)


def table(name, doc, items):
    rows = "\n".join(f'    ("{esc(k)}", "{esc(g)}", "{r}"),' for k, (g, r) in sorted(items.items()))
    return f"/// {doc}\npub static {name}: &[(&str, &str, &str)] = &[\n{rows}\n];\n"


names = read("filenames.lua")
exts = {k.lower(): v for k, v in read("extensions.lua").items()}
special = read("special.lua")
for kind in ("directory", "file"):
    if kind not in special:
        sys.exit(f"special.lua has no `{kind}`")
out = (
    "//! File icons: generated by scripts/gen-icons.py from lvim-icons' data;\n"
    "//! do not edit by hand. (name, Nerd Font glyph, palette role), sorted.\n\n"
    + table("FILENAMES", "Exact file names.", names)
    + "\n"
    + table("EXTENSIONS", "Extensions, lower case, without the dot (also multi-dot tails).", exts)
    + "\n"
    + f'/// A directory.\npub const DIRECTORY: (&str, &str) = ("{esc(special["directory"][0])}", "{special["directory"][1]}");\n'
    + f'/// Any other file.\npub const FILE: (&str, &str) = ("{esc(special["file"][0])}", "{special["file"][1]}");\n'
)
with open(os.path.join(here, "..", "src", "icons.rs"), "w", encoding="utf-8") as f:
    f.write(out)
print(f"src/icons.rs: {len(names)} names, {len(exts)} extensions")
